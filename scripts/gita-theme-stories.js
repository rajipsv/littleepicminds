function getMoralStory(lessonIdea, level, idx) {
  if (level === 'warriors') return null;
  if (SCENARIOS[lessonIdea]?.[level]) {
    const s = SCENARIOS[lessonIdea][level];
    return {
      title: s.title,
      title_te: s.title_te,
      storyTitle: s.storyTitle,
      storyTitle_te: s.storyTitle_te,
      content: s.content,
      content_te: s.content_te,
      activity: s.activity,
      activity_te: s.activity_te,
      emoji: EMOJIS[idx % EMOJIS.length],
    };
  }
  const filled = fillFromTemplate(lessonIdea, level, idx);
  if (!filled) return null;
  return { ...filled, emoji: EMOJIS[idx % EMOJIS.length] };
}

